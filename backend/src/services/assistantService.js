/**
 * Detect user intent based on multilingual keywords
 */
function detectIntent(message) {
  if (!message) return 'default';
  const text = message.toLowerCase();

  // Emergency triggers
  if (
    text.includes('emergency') || text.includes('108') || text.includes('ambulance') ||
    text.includes('chest pain') || text.includes('நெஞ்சு') || text.includes('அவசரம்') ||
    text.includes('आपात') || text.includes('दर्द') || text.includes('छाती') ||
    text.includes('అత్యవసర') || text.includes('জরুরি') || text.includes('ہنگامی')
  ) {
    return 'emergency';
  }

  // Appointment triggers
  if (
    text.includes('appointment') || text.includes('book') || text.includes('doctor') ||
    text.includes('சந்திப்பு') || text.includes('பதிவு') || text.includes('மருத்துவர்') ||
    text.includes('अपॉइंटमेंट') || text.includes('डॉक्टर') || text.includes('బుకింగ్') ||
    text.includes('ডাক্তার') || text.includes('ڈاکٹر')
  ) {
    return 'appointment';
  }

  // ABHA triggers
  if (
    text.includes('abha') || text.includes('card') || text.includes('digital health') ||
    text.includes('ஆபா') || text.includes('அட்டை') || text.includes('आभा') ||
    text.includes('కార్డు') || text.includes('কার্ড') || text.includes('کارڈ')
  ) {
    return 'abha';
  }

  // Symptoms / Fever triggers
  if (
    text.includes('fever') || text.includes('cough') || text.includes('cold') || text.includes('headache') ||
    text.includes('காய்ச்சல்') || text.includes('இருமல்') || text.includes('தலைவலி') ||
    text.includes('बुखार') || text.includes('खांसी') || text.includes('ज्वर') ||
    text.includes('జ్వరం') || text.includes('জ্বর') || text.includes('بخار')
  ) {
    return 'symptoms';
  }

  return 'default';
}

/**
 * Processes chat query and returns localized healthcare answer with disclaimer
 */
function handleAssistantMessage({ message, rawLocale }) {
  const locale = normalizeLocale(rawLocale);
  const intent = detectIntent(message);

  const responseTemplate = ASSISTANT_RESPONSES[intent];
  const replyText = responseTemplate[locale] || responseTemplate['en'];
  const disclaimerText = CLINICAL_DISCLAIMER[locale] || CLINICAL_DISCLAIMER['en'];

  return {
    reply: replyText,
    intent,
    locale,
    disclaimer: disclaimerText,
    timestamp: new Date().toISOString()
  };
}

module.exports = {
  handleAssistantMessage,
  detectIntent,
  ASSISTANT_RESPONSES,
  CLINICAL_DISCLAIMER
};
